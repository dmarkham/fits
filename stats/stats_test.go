// f64Digest is gen_golden.py digest_f64: sha256 of float64 values as
// big-endian IEEE bits, and some of the values by index.
type f64Digest struct {
	SHA256 string          `json:"sha256"`
	Sample map[string]jnum `json:"sample"`
}

// check reports the first difference between got and the digest: a
// sampled value, else the digest itself.
func (d f64Digest) check(got []float64) error {
	if d.SHA256 == "" || len(d.Sample) == 0 {
		return fmt.Errorf("empty digest in golden")
	}
	for k, w := range d.Sample {
		i, err := strconv.Atoi(k)
		if err != nil || i < 0 {
			return fmt.Errorf("bad sample index %q", k)
		}
		if i >= len(got) {
			return fmt.Errorf("%d values, golden samples index %d", len(got), i)
		}
		if math.Float64bits(got[i]) != math.Float64bits(float64(w)) {
			return fmt.Errorf("[%d] = %.17g want %.17g", i, got[i], float64(w))
		}
	}
	if s := sha64(got); s != d.SHA256 {
		return fmt.Errorf("sha256 %s want %s (samples agree)", s, d.SHA256)
	}
	return nil
}

type inputCycle struct {
	Pattern []jnum
	Repeats int
}

func (c *inputCycle) UnmarshalJSON(b []byte) error {
	var pair []json.RawMessage
	if err := json.Unmarshal(b, &pair); err != nil {
		return err
	}
	if len(pair) != 2 {
		return fmt.Errorf("input cycle %s: want [pattern, repeats]", b)
	}
	if err := json.Unmarshal(pair[0], &c.Pattern); err != nil {
		return err
	}
	return json.Unmarshal(pair[1], &c.Repeats)
}

type inputRun struct {
	Value jnum
	Count int
}

func (r *inputRun) UnmarshalJSON(b []byte) error {
	var pair []json.RawMessage
	if err := json.Unmarshal(b, &pair); err != nil {
		return err
	}
	if len(pair) != 2 {
		return fmt.Errorf("input run %s: want [value, count]", b)
	}
	if err := json.Unmarshal(pair[0], &r.Value); err != nil {
		return err
	}
	return json.Unmarshal(pair[1], &r.Count)
}

