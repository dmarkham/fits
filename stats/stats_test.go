// jnum is a golden float: a JSON number, or "nan" / "inf" / "-inf".
type jnum float64

func (j *jnum) UnmarshalJSON(b []byte) error {
	var s string
	if err := json.Unmarshal(b, &s); err == nil {
		switch s {
		case "nan":
			*j = jnum(math.NaN())
		case "inf":
			*j = jnum(math.Inf(1))
		case "-inf":
			*j = jnum(math.Inf(-1))
		default:
			return fmt.Errorf("bad golden float %q", s)
		}
		return nil
	}
	var f float64
	if err := json.Unmarshal(b, &f); err != nil {
		return err
	}
	*j = jnum(f)
	return nil
}

