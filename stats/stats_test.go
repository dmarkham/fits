var (
	goldenOnce  sync.Once
	goldenCases map[string]goldenCase
	goldenErr   error
)

func loadGoldens(t *testing.T) map[string]goldenCase {
	t.Helper()
	goldenOnce.Do(func() {
		data, err := testutil.ReadGolden(statsGoldenPath)
		if err != nil {
			goldenErr = fmt.Errorf("golden %s missing (committed file; regenerate with testdata/gen_golden.py): %v", statsGoldenPath, err)
			return
		}
		var cases map[string]goldenCase
		if err := json.Unmarshal(data, &cases); err != nil {
			goldenErr = err
			return
		}
		for name, c := range cases {
			if c.Formula != nil && c.InputSHA256 == "" {
				goldenErr = fmt.Errorf("%s: formula input without input_sha256", name)
				return
			}
			if c.Formula != nil && c.Dtype == "float64" {
				d, err := formulaValues64(*c.Formula, c.Len)
				if err != nil {
					goldenErr = fmt.Errorf("%s: %v", name, err)
					return
				}
				for _, v := range d {
					c.Input = append(c.Input, jnum(v))
				}
				cases[name] = c
			} else if c.Formula != nil {
				d, err := formulaValues(*c.Formula, c.Len)
				if err != nil {
					goldenErr = fmt.Errorf("%s: %v", name, err)
					return
				}
				for _, v := range d {
					c.Input = append(c.Input, jnum(v))
				}
				c.Dtype = "float32"
				cases[name] = c
			}
			if c.Formula != nil {
				var got string
				if c.Dtype == "float32" {
					f := make([]float32, len(c.Input))
					for i, v := range c.Input {
						f[i] = float32(v)
					}
					got = sha32(f)
				} else {
					f := make([]float64, len(c.Input))
					for i, v := range c.Input {
						f[i] = float64(v)
					}
					got = sha64(f)
				}
				if got != c.InputSHA256 {
					goldenErr = fmt.Errorf("%s: regenerated %s formula input sha256 %s, gen_golden.py used %s", name, c.Formula.Kind, got, c.InputSHA256)
					return
				}
			}
			if c.InputCycle != nil {
				if c.InputCycle.Repeats <= 0 || len(c.InputCycle.Pattern) == 0 {
					goldenErr = fmt.Errorf("%s: bad input cycle", name)
					return
				}
				for range c.InputCycle.Repeats {
					c.Input = append(c.Input, c.InputCycle.Pattern...)
				}
				cases[name] = c
			}
			for _, r := range c.InputRuns {
				if r.Count <= 0 {
					goldenErr = fmt.Errorf("%s: bad run count %d", name, r.Count)
					return
				}
				for range r.Count {
					c.Input = append(c.Input, r.Value)
				}
				cases[name] = c
			}
			if c.InputInt != "" {
				for _, f := range strings.Fields(c.InputInt) {
					v, err := strconv.ParseFloat(f, 64) // correctly rounded
					if err != nil {
						goldenErr = fmt.Errorf("%s: bad integer %q", name, f)
						return
					}
					c.Input = append(c.Input, jnum(v))
				}
				cases[name] = c
			}
			if c.InputF32 != "" || (c.Dtype == "float32" && c.Len == 0) {
				for _, h := range strings.Fields(c.InputF32) {
					u, err := strconv.ParseUint(h, 16, 32)
					if err != nil {
						goldenErr = fmt.Errorf("%s: bad hex %q", name, h)
						return
					}
					c.Input = append(c.Input, jnum(math.Float32frombits(uint32(u))))
				}
				cases[name] = c
			}
			if len(cases[name].Input) != c.Len {
				goldenErr = fmt.Errorf("%s: %d input values, len %d", name, len(cases[name].Input), c.Len)
				return
			}
		}
		for _, name := range requiredGoldenCases {
			if _, ok := cases[name]; !ok {
				goldenErr = fmt.Errorf("golden case %q missing from %s", name, statsGoldenPath)
				return
			}
		}
		goldenCases = cases
	})
	if goldenErr != nil {
		t.Fatal(goldenErr)
	}
	return goldenCases
}

func sortedNames(cases map[string]goldenCase) []string {
	names := make([]string, 0, len(cases))
	for n := range cases {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

// statsInput gives the tests one view of a golden input in its own
// element type, so the generic code is exercised with the real type.
type statsInput interface {
	minMax() (float64, float64)
	mean() float64
	meanStdev() (float64, float64)
	twoPass() (float64, float64)
	sigmaClip(kLow, kHigh float64, maxIter int, cf CenterFunc) SigmaClipResult
	percentile(p float64) float64
	histogram(nbins int) (Histogram, error)
	// moments returns n, Σ|x| and Σx² over the non-NaN values (for
	// rounding-error bounds only).
	moments() (n int, sumAbs, sumSq float64)
}

type typed[T Numeric] struct{ d []T }

func (s typed[T]) minMax() (float64, float64) {
	mn, mx := MinMax(s.d)
	return float64(mn), float64(mx)
}
func (s typed[T]) mean() float64                          { return Mean(s.d) }
func (s typed[T]) meanStdev() (float64, float64)          { return MeanStdev(s.d) }
func (s typed[T]) twoPass() (float64, float64)            { return MeanStdevTwoPass(s.d) }
func (s typed[T]) histogram(nbins int) (Histogram, error) { return BuildHistogram(s.d, nbins) }
func (s typed[T]) sigmaClip(kLow, kHigh float64, maxIter int, cf CenterFunc) SigmaClipResult {
	return SigmaClip(s.d, kLow, kHigh, maxIter, cf)
}
func (s typed[T]) percentile(p float64) float64 { return Percentile(s.d, p) }
func (s typed[T]) moments() (int, float64, float64) {
	n := 0
	var a, q float64
	for _, v := range s.d {
		if v != v {
			continue
		}
		x := float64(v)
		a += math.Abs(x)
		q += x * x
		n++
	}
	return n, a, q
}

func typedOf[T Numeric](t *testing.T, in []jnum) typed[T] {
	t.Helper()
	out := make([]T, len(in))
	for i, v := range in {
		out[i] = T(v)
		if f := float64(out[i]); f != float64(v) && !(f != f && v != v) {
			t.Fatalf("golden input %v not representable", v)
		}
	}
	return typed[T]{out}
}

// typedInts parses the exact decimal integers of an integer golden input
// (int64/uint64 values beyond 2^53 are not float64 values).
func typedInts[T Numeric](t *testing.T, c goldenCase, signed bool, bits int) typed[T] {
	t.Helper()
	fields := strings.Fields(c.InputInt)
	if len(fields) != c.Len {
		t.Fatalf("input_int has %d values, len %d", len(fields), c.Len)
	}
	out := make([]T, len(fields))
	for i, f := range fields {
		if signed {
			v, err := strconv.ParseInt(f, 10, bits)
			if err != nil {
				t.Fatalf("bad %d-bit integer %q: %v", bits, f, err)
			}
			out[i] = T(v)
		} else {
			v, err := strconv.ParseUint(f, 10, bits)
			if err != nil {
				t.Fatalf("bad %d-bit unsigned integer %q: %v", bits, f, err)
			}
			out[i] = T(v)
		}
	}
	return typed[T]{out}
}

func input(t *testing.T, c goldenCase) statsInput {
	t.Helper()
	if c.Gotype != "" {
		if c.Gotype == "namedf32" && c.Dtype == "float32" {
			return typedOf[namedF32](t, c.Input)
		}
		t.Fatalf("unknown gotype %q for dtype %q", c.Gotype, c.Dtype)
	}
	switch c.Dtype {
	case "float32":
		return typedOf[float32](t, c.Input)
	case "float64":
		return typedOf[float64](t, c.Input)
	case "int8":
		return typedInts[int8](t, c, true, 8)
	case "int16":
		return typedInts[int16](t, c, true, 16)
	case "int32":
		return typedInts[int32](t, c, true, 32)
	case "int64":
		return typedInts[int64](t, c, true, 64)
	case "uint8":
		return typedInts[uint8](t, c, false, 8)
	case "uint16":
		return typedInts[uint16](t, c, false, 16)
	case "uint32":
		return typedInts[uint32](t, c, false, 32)
	case "uint64":
		return typedInts[uint64](t, c, false, 64)
	}
	t.Fatalf("unknown dtype %q", c.Dtype)
	return nil
}

// gamma is Higham's γ_n = n·u/(1-n·u), u = 2^-53: the relative error
// bound of an n-term recursive float64 sum.
func gamma(n int) float64 {
	u := math.Ldexp(1, -53)
	return float64(n) * u / (1 - float64(n)*u)
}

// ulpDiff is the distance between a and b in float64 ULPs.
func ulpDiff(a, b float64) uint64 {
	ord := func(f float64) int64 {
		i := int64(math.Float64bits(f))
		if i < 0 {
			i = math.MinInt64 - i
		}
		return i
	}
	d := ord(a) - ord(b)
	if d < 0 {
		d = -d
	}
	return uint64(d)
}

func finite(f float64) bool { return !math.IsNaN(f) && !math.IsInf(f, 0) }

// beyond reports whether got is NOT within tol of want. It is NaN-aware:
// a NaN on one side only is always beyond (math.Abs(got-want) > tol is
// false for a NaN got, so a function returning NaN would pass), both NaN
// is within, and equal infinities are within.
func beyond(got, want, tol float64) bool {
	if math.IsNaN(got) || math.IsNaN(want) {
		return !(math.IsNaN(got) && math.IsNaN(want))
	}
	if got == want {
		return false
	}
	return !(math.Abs(got-want) <= tol)
}

// fpClass is "nan", "+inf", "-inf" or "finite".
func fpClass(f float64) string {
	switch {
	case math.IsNaN(f):
		return "nan"
	case math.IsInf(f, 1):
		return "+inf"
	case math.IsInf(f, -1):
		return "-inf"
	}
	return "finite"
}

// sameClass: both NaN, or equal (including equal infinities).
func sameClass(a, b float64) bool { return (a != a && b != b) || a == b }

func TestMinMax(t *testing.T) {
	cases := loadGoldens(t)
	for _, name := range sortedNames(cases) {
		c := cases[name]
		t.Run(name, func(t *testing.T) {
			mn, mx := input(t, c).minMax()
			if c.Min == nil {
				if mn != 0 || mx != 0 {
					t.Errorf("empty/all-NaN: got (%g, %g) want (0, 0)", mn, mx)
				}
				return
			}
			if mn != float64(*c.Min) || mx != float64(*c.Max) {
				t.Errorf("got (%g, %g) want numpy (%g, %g)", mn, mx, float64(*c.Min), float64(*c.Max))
			}
		})
	}
}

// TestMean checks Mean against the exact rational mean, within the
// recursive-summation bound its doc states (plus the final division).
func TestMean(t *testing.T) {
	cases := loadGoldens(t)
	for _, name := range sortedNames(cases) {
		c := cases[name]
		t.Run(name, func(t *testing.T) {
			in := input(t, c)
			got := in.mean()
			n, sumAbs, _ := in.moments()
			switch {
			case n == 0:
				if got != 0 {
					t.Errorf("empty: got %g want 0", got)
				}
			case c.ExactMean != nil && finite(float64(*c.Mean)):
				want := float64(*c.ExactMean)
				tol := gamma(n+1) * sumAbs / float64(n)
				if beyond(got, want, tol) {
					t.Errorf("got %.17g want exact %.17g (|diff| %g > bound %g)", got, want, math.Abs(got-want), tol)
				}
			default:
				// ±Inf in the data: IEEE propagation, as numpy.
				if !sameClass(got, float64(*c.Mean)) {
					t.Errorf("got %v want numpy %v", got, float64(*c.Mean))
				}
			}
		})
	}
}

// TestMeanStdev_Numpy: MeanStdev agrees with numpy std(ddof=1) within the
// rounding-error bound of the one-pass formula stated in its doc. The
// bound is derived from recursive summation (Higham): |Δ(Σx²)| and
// |Δ(n·mean²)| are each ≤ γ_{n+3}·Σx², so |Δvar| ≤ 2γ_{n+3}Σx²/(n-1) and
// |Δσ| = |Δvar|/(σ_got+σ_numpy), plus a few ULP for numpy's own rounding.
func TestMeanStdev_Numpy(t *testing.T) {
	cases := loadGoldens(t)
	for _, name := range sortedNames(cases) {
		c := cases[name]
		t.Run(name, func(t *testing.T) {
			in := input(t, c)
			mean, stdev := in.meanStdev()
			n, sumAbs, sumSq := in.moments()
			if n < 2 {
				var wantMean float64
				if n == 1 {
					wantMean = float64(*c.Mean)
				}
				if mean != wantMean || stdev != 0 {
					t.Errorf("n=%d: got (%g, %g) want (%g, 0)", n, mean, stdev, wantMean)
				}
				return
			}
			if c.ExactMean == nil || !finite(float64(*c.Stdev)) {
				// Non-finite data (±Inf, or Σx² overflowing): the
				// documented IEEE propagation, on every architecture
				// (TestMeanStdev_OnePassFormula pins the bits only where
				// the fusion model is measured). The mean has no
				// multiply-add, so it is the formula's bit for bit; the
				// stdev's class (NaN / ±Inf / finite) is the same in all
				// three fusion models, and MeanStdev must give it.
				if !same64(mean, float64(c.OnepassMean)) {
					t.Errorf("mean %v, want the formula's %v", mean, float64(c.OnepassMean))
				}
				want := fpClass(float64(c.OnepassStdev))
				if fpClass(float64(c.OnepassStdevFMAAcc)) != want || fpClass(float64(c.OnepassStdevFMAAll)) != want {
					t.Fatalf("golden fusion models disagree on the stdev class: %v %v %v",
						float64(c.OnepassStdev), float64(c.OnepassStdevFMAAcc), float64(c.OnepassStdevFMAAll))
				}
				if got := fpClass(stdev); got != want {
					t.Errorf("stdev %v (%s), want %s (numpy std(ddof=1) %v)", stdev, got, want, float64(*c.Stdev))
				}
				return
			}
			wantMean, wantSD := float64(*c.Mean), float64(*c.Stdev)
			if tol := 2 * gamma(n+2) * sumAbs / float64(n); beyond(mean, wantMean, tol) {
				t.Errorf("mean: got %.17g want numpy %.17g (bound %g)", mean, wantMean, tol)
			}
			tolVar := 2 * gamma(n+3) * sumSq / float64(n-1)
			tol := tolVar/(stdev+wantSD) + 8*math.Ldexp(wantSD, -53)
			if beyond(stdev, wantSD, tol) {
				t.Errorf("stdev: got %.17g want numpy %.17g (|diff| %g > bound %g)", stdev, wantSD, math.Abs(stdev-wantSD), tol)
			}
		})
	}
}

// onepassStdevForBuild is the golden one-pass stdev for this build's
// fusion model (ok false when the architecture has no measured model).
func onepassStdevForBuild(c goldenCase) (float64, bool) {
	switch fusionModel {
	case "none":
		return float64(c.OnepassStdev), true
	case "fma_acc":
		return float64(c.OnepassStdevFMAAcc), true
	case "fma_all":
		return float64(c.OnepassStdevFMAAll), true
	}
	return 0, false
}

// TestMeanStdev_OnePassFormula pins MeanStdev to the formula its doc
// states, bit for bit: gen_golden.py evaluates that formula in Python
// (IEEE double, same operation order) once per fusion model, because the
