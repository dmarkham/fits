// TestPercentile_RangeOverflow pins the documented result when max-min
// overflows the working precision (float32 for []float32, float64
// otherwise): the histogram scale is 0 and Siril's bin index is a cast of
// NaN (undefined behaviour in C), so there is no oracle; the result is
// NaN for every p, as for ±Inf data, and MAD is NaN.
func TestPercentile_RangeOverflow(t *testing.T) {
	f32 := []float32{-3e38, 3e38, 1}
	f64 := []float64{-1e308, 1e308, 5}
	for _, p := range []float64{0, 0.25, 0.5, 1} {
		if got := Percentile(f32, p); !math.IsNaN(got) {
			t.Errorf("float32 Percentile(%v, %g) = %v want NaN", f32, p, got)
		}
		if got := Percentile(f64, p); !math.IsNaN(got) {
			t.Errorf("float64 Percentile(%v, %g) = %v want NaN", f64, p, got)
		}
	}
	if med, mad := MADWithMedian(f32); !math.IsNaN(med) || !math.IsNaN(mad) {
		t.Errorf("float32 MADWithMedian = (%v, %v) want NaN", med, mad)
	}
	if med, mad := MADWithMedian(f64); !math.IsNaN(med) || !math.IsNaN(mad) {
		t.Errorf("float64 MADWithMedian = (%v, %v) want NaN", med, mad)
	}
	// Just inside the range: finite and within [min, max].
	if got := Percentile([]float64{-8e307, 8e307, 5}, 0.5); math.IsNaN(got) || got < -8e307 || got > 8e307 {
		t.Errorf("finite range: Percentile = %v", got)
	}
}
