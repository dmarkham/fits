// TestBuildHistogram_Numpy: counts and edges bit-identical to
// numpy.histogram of the finite float64 values, CDF identical to
// cumsum(counts)/total, Percentile within 4 ULP of the exact-arithmetic
// evaluation of its documented definition; ErrHistogramRange and a zero
// Histogram wherever numpy raises.
func TestBuildHistogram_Numpy(t *testing.T) {
	cases := loadGoldens(t)
	for _, name := range sortedNames(cases) {
		c := cases[name]
		if c.Histogram == nil {
			continue
		}
		t.Run(name, func(t *testing.T) {
			in := input(t, c)
			want := c.Histogram
			h, err := in.histogram(want.NBins)
			if want.NumpyError != "" {
				// numpy raises: BuildHistogram must return the error and
				// no histogram.
				if !errors.Is(err, ErrHistogramRange) || h.NBins != 0 || h.Counts != nil || h.Edges != nil || h.Total != 0 {
					t.Errorf("numpy raises (%s): got err %v, histogram %+v; want ErrHistogramRange and a zero Histogram", want.NumpyError, err, h)
				}
				return
			}
			if err != nil {
				t.Fatalf("numpy bins this input; BuildHistogram: %v", err)
			}
			if h.NBins != want.NBins || len(h.Counts) != want.NBins || len(h.Edges) != want.NBins+1 {
				t.Fatalf("shape: nbins %d counts %d edges %d", h.NBins, len(h.Counts), len(h.Edges))
			}
			var total int64
			for i := range want.Counts {
				total += want.Counts[i]
				if h.Counts[i] != want.Counts[i] {
					t.Errorf("bin %d: count %d want %d", i, h.Counts[i], want.Counts[i])
				}
			}
			if h.Total != total {
				t.Errorf("total %d want %d", h.Total, total)
			}
			if err := want.Edges.check(h.Edges); err != nil {
				t.Errorf("edges vs numpy: %v", err)
			}
			if err := want.CDF.check(h.CDF()); err != nil {
				t.Errorf("CDF vs numpy cumsum(counts)/total: %v", err)
			}
			maxEdge := math.Max(math.Abs(h.Edges[0]), math.Abs(h.Edges[h.NBins]))
			tol := 4 * math.Ldexp(maxEdge, -52)
			if len(want.Percentiles) == 0 {
				t.Fatal("no histogram percentiles in golden")
			}
			for ps, wp := range want.Percentiles {
				p, err := strconv.ParseFloat(ps, 64)
				if err != nil {
					t.Fatal(err)
				}
				if got := h.Percentile(p); beyond(got, float64(wp), tol) {
					t.Errorf("Percentile(%s) = %.17g want %.17g (tol %g)", ps, got, float64(wp), tol)
				}
			}
		})
	}
}

// TestHistogramPercentile_Scipy checks Histogram.Percentile against an
// implementation it shares nothing with: scipy.stats.rv_histogram's ppf,
// the quantile function of the same piecewise-linear distribution
// (gen_golden.py scipy_hist_ppf), for 0 < p < 1 wherever the CDF is not
// flat at p (there every point of the flat part is a p-quantile; the
// documented left end is checked by TestBuildHistogram_Numpy).
//
// Tolerance: scipy normalises and accumulates the bin masses in floating
// point, so its CDF is off by up to about (nbins+2)·ε; inverted inside a
// bin of count c that moves the result by that times Total/c bin widths.
// Add 4 ULP of the edge magnitude for the interpolation itself. A bin, or
// half a bin, off is many orders of magnitude outside it.
func TestHistogramPercentile_Scipy(t *testing.T) {
	cases := loadGoldens(t)
	checked := 0
	for _, name := range sortedNames(cases) {
		c := cases[name]
		if c.Histogram == nil || c.Histogram.NumpyError != "" {
			continue
		}
		t.Run(name, func(t *testing.T) {
			h, err := input(t, c).histogram(c.Histogram.NBins)
			if err != nil {
				t.Fatal(err)
			}
			eps := math.Ldexp(1, -52)
			ulp4 := 4 * eps * math.Max(math.Abs(h.Edges[0]), math.Abs(h.Edges[h.NBins]))
			for ps, wp := range c.Histogram.ScipyPPF {
				p, err := strconv.ParseFloat(ps, 64)
				if err != nil {
					t.Fatal(err)
				}
				want := float64(wp)
				// The non-empty bin holding scipy's answer.
				i := sort.SearchFloat64s(h.Edges, want)
				if i > 0 && (i > h.NBins || h.Edges[i] > want) {
					i--
				}
				i = min(i, h.NBins-1)
				for i > 0 && h.Counts[i] == 0 {
					i--
				}
				width := h.Edges[i+1] - h.Edges[i]
				tol := float64(h.NBins+4)*eps*float64(h.Total)/float64(h.Counts[i])*width + ulp4
				if got := h.Percentile(p); beyond(got, want, tol) {
					t.Errorf("Percentile(%s) = %.17g, scipy rv_histogram ppf %.17g (|diff| %g > %g)", ps, got, want, math.Abs(got-want), tol)
				}
				checked++
			}
		})
	}
	if checked < 150 {
		t.Errorf("only %d histogram percentiles checked against scipy", checked)
	}
	t.Logf("%d histogram percentiles agree with scipy rv_histogram.ppf", checked)
}

