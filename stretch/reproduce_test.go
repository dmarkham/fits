// sirilOwned reports whether a committed golden file (path relative to
// testdata/golden) is written by gen_siril_goldens.py; the rest are
// gen_clahe_cv2.py's (cv2_* inputs, the cv2 JSON files) or
// siril_cli_sha256.json (siril_cli_digests.py).
func sirilOwned(rel string) bool {
	switch {
	case strings.HasPrefix(rel, "sref/"), strings.HasPrefix(rel, "sweep/"):
		return true
	case strings.HasPrefix(rel, "inputs/"):
		return !strings.HasPrefix(rel, "inputs/cv2_")
	case strings.HasPrefix(rel, "stretch_"):
		return rel != "stretch_clahe_cv2.json"
	}
	return false
}

func goldenFiles(t *testing.T, dir string, keep func(string) bool) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		if keep(filepath.ToSlash(rel)) {
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(out)
	return out
}

// sameGoldenSet requires the generator output in dir to be exactly the
// committed files selected by keep, byte for byte.
func sameGoldenSet(t *testing.T, dir string, keep func(string) bool) {
	t.Helper()
	got := goldenFiles(t, dir, func(string) bool { return true })
	want := goldenFiles(t, goldenDir, keep)
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("generator wrote %d files, %d committed:\n got  %v\n want %v", len(got), len(want), got, want)
	}
	n := 0
	for _, rel := range got {
		g, err := os.ReadFile(filepath.Join(dir, rel))
		if err != nil {
			t.Fatal(err)
		}
		w, err := os.ReadFile(filepath.Join(goldenDir, rel))
		if err != nil {
			t.Errorf("%s: written by the generator, not committed", rel)
			continue
		}
		if strings.HasSuffix(rel, ".gz") {
			// gzipped golden: compare the JSON inside (the compressed
			// bytes depend on the zlib build)
			gu, gerr := testutil.Gunzip(g)
			wu, werr := testutil.Gunzip(w)
			if gerr != nil || werr != nil {
				t.Errorf("%s: gzip: regenerated %v, committed %v", rel, gerr, werr)
				continue
			}
			g, w = gu, wu
		}
		if !bytes.Equal(g, w) {
			t.Errorf("%s: regenerated bytes differ from the committed golden (%d vs %d bytes)", rel, len(g), len(w))
			continue
		}
		n++
	}
	t.Logf("%d files reproduced byte for byte", n)
}

type sirilCLIDigests struct {
	Input struct {
		Blob   string `json:"blob"`
		Shape  []int  `json:"shape"`
		SHA256 string `json:"sha256"`
	} `json:"input"`
	Presets map[string]struct {
		Command string `json:"command"`
		Blob    string `json:"blob"`
		Shape   []int  `json:"shape"`
		SHA256  string `json:"sha256"`
	} `json:"presets"`
}

// TestSirilCLIDigests ties the 18 preset goldens to the real siril-cli
// output: golden/siril_cli_sha256.json holds the canonical digest of each
// original siril-cli pixel file (and of its input) as committed in
// c17580b, and every stretch_<preset>.json must carry that digest for the
// same command on that input. No tools needed.
func TestSirilCLIDigests(t *testing.T) {
	var d sirilCLIDigests
	readGolden(t, "siril_cli_sha256.json", &d)
	if len(d.Presets) != 18 {
		t.Fatalf("%d siril-cli digests, want 18", len(d.Presets))
	}
	for _, p := range DefaultPresets() {
		w, ok := d.Presets[p.Name]
		if !ok {
			t.Errorf("no siril-cli digest for preset %s", p.Name)
			continue
		}
		c := loadCLI(t, p.Name)
		if c.Command != w.Command || c.Command != p.Command {
			t.Errorf("%s: golden command %q, siril-cli %q, preset %q", p.Name, c.Command, w.Command, p.Command)
		}
		if c.Out.SHA256 != w.SHA256 {
			t.Errorf("%s: golden output sha256 %s, siril-cli %s", p.Name, c.Out.SHA256, w.SHA256)
		}
		if c.Input.SHA256 != d.Input.SHA256 || c.Input.File != "inputs/synth.f32" {
			t.Errorf("%s: input %s %s, siril-cli input %s", p.Name, c.Input.File, c.Input.SHA256, d.Input.SHA256)
		}
		c.Input.f32(t) // the committed input file has that digest
	}
}

// manifest lists the golden/sref cases.
func manifest(t *testing.T) []string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(goldenDir, "sref", "MANIFEST"))
	if err != nil {
		t.Fatalf("golden manifest: %v", err)
	}
	return strings.Fields(string(b))
}

// TestSrefManifest: every golden/sref file is listed in MANIFEST and
// loads, and every listed case is named by a test (preset_* cases are
// loaded by TestDefaultPresets_SirilOracle from the preset names), so a
// case cannot silently drop out of the suite.
func TestSrefManifest(t *testing.T) {
	names := manifest(t)
	files := goldenFiles(t, filepath.Join(goldenDir, "sref"), func(rel string) bool { return strings.HasSuffix(rel, ".json") })
	if len(files) != len(names) {
		t.Errorf("%d golden/sref files, %d in MANIFEST", len(files), len(names))
	}
	src := testSources(t)
	for _, n := range names {
		var raw map[string]json.RawMessage
		readGolden(t, filepath.Join("sref", n+".json"), &raw)
		if !strings.Contains(src, `"`+n+`"`) && !strings.HasPrefix(n, "preset_") {
			t.Errorf("golden sref/%s.json is not used by name in any test", n)
		}
	}
}

func testSources(t *testing.T) string {
	t.Helper()
	m, err := filepath.Glob("*_test.go")
	if err != nil || len(m) == 0 {
		t.Fatal("no test sources")
	}
	var b strings.Builder
	for _, f := range m {
		s, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		b.Write(s)
	}
	return b.String()
}
