// TestCrefGoldensReproduce: every golden of compress/testdata/cref
// (quantizer, noise estimator, dither table, RICE/HCOMPRESS/PLIO
// encoders, the 96 fits_img_compress cases of golden/img -- 91 images plus
// 5 cfitsio refusals -- the 20 BITPIX -64 cases of golden/img64, the 5
// round-3 fits_img_compress cases of golden/img2, the 5 images compressed
// while written by fits_write_imgnull (golden/imgw), the source images,
// their decode digests and the input hashes) is regenerated by the
// libcfitsio harness and byte-compared (make verify; the committed
// .fits.gz files are inflated first, so the comparison is on the bytes
// cfitsio wrote).
func TestCrefGoldensReproduce(t *testing.T) {
	testutil.RequireGoldenPlatform(t)
	testutil.MakeVerify(t, "testdata/cref", []string{"cref"}, []string{"verify"})
}
