// Writer-parity tests: the Go encoders must produce exactly the bytes the
// real libcfitsio encoders produce for the same input. The goldens come
// from `cref encode` (compress/testdata/cref/cref.c), which calls
// fits_rcomp / fits_rcomp_short / fits_rcomp_byte, fits_hcompress /
// fits_hcompress64 and pl_p2li from the system libcfitsio 4.7.0, on
// deliberately adversarial input (full-range jumps whose differences
// overflow the pixel width, literal/zero/normal Rice blocks, odd tile
// sizes, PLIO values up to 2^24-1). Byte equality with cfitsio's own
// output means every reader decodes our tiles exactly as it decodes
// cfitsio's. The inputs are regenerated by internal/crefgen (a port of
// cref.c's generators) and must hash to the input cfitsio was given.

const encGoldenDir = "testdata/cref/golden"

// Expected number of cases of each kind in golden/MANIFEST. Keeping the
// counts here means a truncated MANIFEST (or a partial deletion of the
// golden tree) fails instead of silently testing less.
var encGoldenCounts = map[string]int{"rice": 24, "hcomp": 20, "plio": 9, "img": 96, "imgw": 5, "img64": 20, "img2": 5}

// encManifest returns kind -> case names from golden/MANIFEST and checks
// that the directory holds exactly the files those cases need.
func encManifest(t *testing.T) map[string][]string {
	t.Helper()
	p := filepath.Join(encGoldenDir, "MANIFEST")
	f, err := os.Open(p)
	if err != nil {
		t.Fatalf("committed golden missing (failure, not a skip): %v", err)
	}
	defer f.Close()
	m := map[string][]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fs := strings.Fields(sc.Text())
		if len(fs) != 2 {
			t.Fatalf("MANIFEST: bad line %q", sc.Text())
		}
		m[fs[0]] = append(m[fs[0]], fs[1])
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	for kind, want := range encGoldenCounts {
		if got := len(m[kind]); got != want {
			t.Fatalf("MANIFEST lists %d %s cases, want %d", got, kind, want)
		}
	}
	if len(m) != len(encGoldenCounts) {
		t.Fatalf("MANIFEST has kinds %v, want exactly %v", keys(m), keys(encGoldenCounts))
	}
	return m
}

func keys[V any](m map[string]V) []string {
	var k []string
	for s := range m {
		k = append(k, s)
	}
	sort.Strings(k)
	return k
}

// TestEncodeGoldensComplete fails if any golden listed in MANIFEST is
// missing, or if a golden file exists that no listed case owns.
func TestEncodeGoldensComplete(t *testing.T) {
	m := encManifest(t)
	exts := map[string][]string{
		"rice":  {".rice", ".json"},
		"hcomp": {".hc", ".json"},
		"plio":  {".plio", ".json"},
	}
	for kind, names := range m {
		owned := map[string]bool{}
		for _, n := range names {
			need := exts[kind]
			if kind == "img" || kind == "imgw" || kind == "img64" || kind == "img2" {
				need = []string{".json"}
				var meta ImgGoldenMeta
				readJSON(t, filepath.Join(encGoldenDir, kind, n+".json"), &meta)
				// cfitsio-written FITS files are committed gzipped
				// (gzip -n -9; make verify compares the inflated bytes)
				if meta.SrcHeader {
					need = append(need, ".src.fits.gz")
				}
				if meta.Status == 0 {
					need = append(need, ".fits.gz")
					// lossy cases carry cfitsio's decode as a digest
					if lossy := meta.Type == "f32" || meta.Type == "f64" || meta.HScale != 0; lossy != (len(meta.Dec) > 0) {
						t.Errorf("img %s: lossy %v but decode digest present %v", n, lossy, len(meta.Dec) > 0)
					}
				}
				if len(meta.InSHA256) != 64 {
					t.Errorf("img %s: no input sha256", n)
				}
			}
			for _, e := range need {
				p := filepath.Join(encGoldenDir, kind, n+e)
				if _, err := os.Stat(p); err != nil {
					t.Errorf("golden missing: %v", err)
				}
				owned[n+e] = true
			}
		}
		ents, err := os.ReadDir(filepath.Join(encGoldenDir, kind))
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range ents {
			if !owned[e.Name()] {
				t.Errorf("golden %s/%s is not owned by any MANIFEST case (untested file)", kind, e.Name())
			}
		}
	}
}

// ImgGoldenMeta is golden/img/<case>.json (see cref.c run_img_case).
type ImgGoldenMeta struct {
	Name             string  `json:"name"`
	Type             string  `json:"type"`
	Naxes            []int64 `json:"naxes"`
	Algo             string  `json:"algo"`
	Tile             []int64 `json:"tile"`
	QLevel           float64 `json:"qlevel"`
	QMethod          int     `json:"qmethod"`
	Seed             int     `json:"seed"`
	HScale           float64 `json:"hscale"`
	LosslessVerified bool    `json:"lossless_verified"`
	SrcHeader        bool    `json:"src_header"`
	WriteImgnull     bool    `json:"write_imgnull"`
	NullValue        float64 `json:"nullvalue"` // imgw: fits_write_imgnull null value (0: -1e30)
	Status           int     `json:"status"`
	Error            string  `json:"error"`
	Kind             int     `json:"kind"`
	GenSeed          uint64  `json:"gen_seed"`
	InSHA256         string  `json:"in_sha256"`
	// Dec is cfitsio's decode (lossy cases), a testutil.Values digest;
	// the root package's tests compare readers against it.
	Dec json.RawMessage `json:"dec"`
}

func readJSON(t *testing.T, path string, v any) {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("committed golden missing (failure, not a skip): %v", err)
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
}

func readGolden(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("committed golden missing (failure, not a skip): %v", err)
	}
	return b
}

// firstDiff describes the first differing byte of two streams.
func firstDiff(got, want []byte) string {
	n := len(got)
	if len(want) < n {
		n = len(want)
	}
	for i := 0; i < n; i++ {
		if got[i] != want[i] {
			return fmt.Sprintf("len got %d want %d; first difference at byte %d: got %#02x want %#02x", len(got), len(want), i, got[i], want[i])
		}
	}
	return fmt.Sprintf("len got %d want %d; common prefix identical", len(got), len(want))
}

// TestRiceEncodeMatchesCfitsio: the RICE_1 encoder vs fits_rcomp,
// fits_rcomp_short and fits_rcomp_byte, byte for byte.
func TestRiceEncodeMatchesCfitsio(t *testing.T) {
	for _, name := range encManifest(t)["rice"] {
		t.Run(name, func(t *testing.T) {
			var meta struct {
				Name      string `json:"name"`
				BytePix   int    `json:"bytepix"`
				N         int    `json:"n"`
				BlockSize int    `json:"blocksize"`
				NBytes    int    `json:"nbytes"`
				Kind      int    `json:"kind"`
				GenSeed   uint64 `json:"gen_seed"`
				InSHA256  string `json:"in_sha256"`
			}
			readJSON(t, filepath.Join(encGoldenDir, "rice", name+".json"), &meta)
			in := crefgen.LEInts(crefgen.IntKind(int64(meta.N), meta.BytePix, meta.Kind, meta.GenSeed), meta.BytePix)
			if err := crefgen.Check(name, in, meta.InSHA256); err != nil {
				t.Fatal(err)
			}
			want := readGolden(t, filepath.Join(encGoldenDir, "rice", name+".rice"))
			if len(in) != meta.N*meta.BytePix || len(want) != meta.NBytes {
				t.Fatalf("golden sizes inconsistent with %s.json", name)
			}
			src := leToBE(in, meta.BytePix)
			enc, err := SelectEncoder(RICE1, Params{"BLOCKSIZE": int64(meta.BlockSize), "BYTEPIX": int64(meta.BytePix)})
			if err != nil {
				t.Fatal(err)
			}
			dst := make([]byte, len(src)*2+1024)
			n, err := enc.Encode(src, dst, meta.N, meta.BytePix)
			if err != nil {
				t.Fatalf("Encode: %v", err)
			}
			if !bytes.Equal(dst[:n], want) {
				t.Fatalf("RICE_1 stream differs from cfitsio: %s", firstDiff(dst[:n], want))
			}
			checkExactBuffer(t, "RICE_1", want, func(d []byte) (int, error) { return enc.Encode(src, d, meta.N, meta.BytePix) })
		})
	}
}

// checkExactBuffer holds an encoder to the Encoder contract at the
// buffer boundary, with cfitsio's stream length as the truth: a dst of
// exactly len(want) bytes yields the whole stream, and one byte less
// yields ErrBufferTooSmall -- never a silently truncated stream.
func checkExactBuffer(t *testing.T, algo string, want []byte, encode func(dst []byte) (int, error)) {
	t.Helper()
	exact := make([]byte, len(want))
	n, err := encode(exact)
	if err != nil || n != len(want) || !bytes.Equal(exact, want) {
		t.Errorf("%s into a %d-byte dst (the stream's exact length): (%d, %v), want the full stream", algo, len(want), n, err)
	}
	if len(want) == 0 {
		return
	}
	short := make([]byte, len(want)-1)
	n, err = encode(short)
	if !errors.Is(err, ErrBufferTooSmall) {
		t.Errorf("%s into a %d-byte dst (one short): (%d, %v), want ErrBufferTooSmall", algo, len(short), n, err)
	}
}

// leToBE converts a little-endian array of width-byte elements (the
// harness's .in.bin layout) to FITS big-endian order.
func leToBE(in []byte, width int) []byte {
	out := make([]byte, len(in))
	for i := 0; i+width <= len(in); i += width {
		for b := 0; b < width; b++ {
			out[i+b] = in[i+width-1-b]
		}
	}
	return out
}

// TestHcompressEncodeMatchesCfitsio: the HCOMPRESS_1 encoder vs
// fits_hcompress (BITPIX 8/16, 32-bit transform) and fits_hcompress64
// (BITPIX 32, 64-bit transform), called the way imcompress.c calls them.
// Includes full-range int32 tiles whose transform overflows 32 bits.
func TestHcompressEncodeMatchesCfitsio(t *testing.T) {
	for _, name := range encManifest(t)["hcomp"] {
		t.Run(name, func(t *testing.T) {
			var meta struct {
				Name     string `json:"name"`
				Bitpix   int    `json:"bitpix"`
				Naxis1   int    `json:"naxis1"`
				Naxis2   int    `json:"naxis2"`
				Scale    int    `json:"scale"`
				NBytes   int    `json:"nbytes"`
				Kind     int    `json:"kind"`
				GenSeed  uint64 `json:"gen_seed"`
				InSHA256 string `json:"in_sha256"`
			}
			readJSON(t, filepath.Join(encGoldenDir, "hcomp", name+".json"), &meta)
			n := meta.Naxis1 * meta.Naxis2
			var vals []int64
			if meta.Kind == 5 {
				vals = crefgen.NoiseImage(int64(n), meta.Bitpix/8, meta.GenSeed)
			} else {
				vals = crefgen.IntKind(int64(n), meta.Bitpix/8, meta.Kind, meta.GenSeed)
			}
			in := crefgen.LEInts(vals, 4)
			if err := crefgen.Check(name, in, meta.InSHA256); err != nil {
				t.Fatal(err)
			}
			want := readGolden(t, filepath.Join(encGoldenDir, "hcomp", name+".hc"))
			if len(in) != n*4 || len(want) != meta.NBytes {
				t.Fatalf("golden sizes inconsistent with %s.json", name)
			}
			width := meta.Bitpix / 8
			src := make([]byte, n*width)
			for i := 0; i < n; i++ {
				v := int32(binary.LittleEndian.Uint32(in[i*4:]))
				switch width {
				case 1:
					src[i] = byte(v) // BITPIX 8 is unsigned on disk
				case 2:
					binary.BigEndian.PutUint16(src[i*2:], uint16(int16(v)))
				case 4:
					binary.BigEndian.PutUint32(src[i*4:], uint32(v))
				}
			}
			enc, err := SelectEncoder(HCOMPRESS1, Params{"SCALE": int64(meta.Scale)})
			if err != nil {
				t.Fatal(err)
			}
			// imcompress.c: fits_hcompress(idata, tilenx, tileny, ...) and
			// the Go encoder's SetShape(nx = slow axis, ny = fast axis).
			enc.(interface{ SetShape(nx, ny int) }).SetShape(meta.Naxis2, meta.Naxis1)
			dst := make([]byte, n*16+1024)
			var got []byte
			func() {
				defer func() {
					if r := recover(); r != nil {
						t.Fatalf("Encode panicked: %v", r)
					}
				}()
				k, err := enc.Encode(src, dst, n, width)
				if err != nil {
					t.Fatalf("Encode: %v", err)
				}
				got = dst[:k]
			}()
			if !bytes.Equal(got, want) {
				t.Fatalf("HCOMPRESS_1 stream differs from cfitsio: %s", firstDiff(got, want))
			}
			checkExactBuffer(t, "HCOMPRESS_1", want, func(d []byte) (int, error) {
				e, _ := SelectEncoder(HCOMPRESS1, Params{"SCALE": int64(meta.Scale)})
				e.(interface{ SetShape(nx, ny int) }).SetShape(meta.Naxis2, meta.Naxis1)
				return e.Encode(src, d, n, width)
			})
		})
	}
}

// TestPLIOEncodeMatchesCfitsio: the PLIO_1 encoder vs pl_p2li. The golden
// is the big-endian int16 line list, i.e. the bytes of the 1PI
// COMPRESSED_DATA cell cfitsio writes.
func TestPLIOEncodeMatchesCfitsio(t *testing.T) {
	for _, name := range encManifest(t)["plio"] {
		t.Run(name, func(t *testing.T) {
			var meta struct {
				Name     string `json:"name"`
				N        int    `json:"n"`
				NWords   int    `json:"nwords"`
				Kind     int    `json:"kind"`
				GenSeed  uint64 `json:"gen_seed"`
				InSHA256 string `json:"in_sha256"`
			}
			readJSON(t, filepath.Join(encGoldenDir, "plio", name+".json"), &meta)
			in := crefgen.LEInts(crefgen.Plio(int64(meta.N), meta.Kind, meta.GenSeed), 4)
			if err := crefgen.Check(name, in, meta.InSHA256); err != nil {
				t.Fatal(err)
			}
			want := readGolden(t, filepath.Join(encGoldenDir, "plio", name+".plio"))
			if len(in) != meta.N*4 || len(want) != meta.NWords*2 {
				t.Fatalf("golden sizes inconsistent with %s.json", name)
			}
			src := leToBE(in, 4)
			enc, _ := SelectEncoder(PLIO1, nil)
			dst := make([]byte, meta.N*8+1024)
			k, err := enc.Encode(src, dst, meta.N, 4)
			if err != nil {
				t.Fatalf("Encode: %v", err)
			}
			if !bytes.Equal(dst[:k], want) {
				t.Fatalf("PLIO_1 line list differs from cfitsio pl_p2li: %s", firstDiff(dst[:k], want))
			}
			checkExactBuffer(t, "PLIO_1", want, func(d []byte) (int, error) { return enc.Encode(src, d, meta.N, 4) })
		})
	}
}

// TestPLIOEncodeRejectsOutOfRange: cfitsio refuses PLIO pixels outside
// [0, 2^24-1] ("data out of range for PLIO compression (0 - 2**24)",
// imcompress.c); the encoder must refuse them too instead of writing a
// line list that decodes to different values.
func TestPLIOEncodeRejectsOutOfRange(t *testing.T) {
	enc, _ := SelectEncoder(PLIO1, nil)
	for _, v := range []int32{-1, -32768, 16777216, 1 << 30} {
		src := make([]byte, 3*4)
		binary.BigEndian.PutUint32(src[4:], uint32(v))
		_, err := enc.Encode(src, make([]byte, 1024), 3, 4)
		if err == nil {
			t.Errorf("PLIO_1 encoded out-of-range pixel %d without error", v)
			continue
		}
		if !errors.Is(err, ErrPLIORange) {
			t.Errorf("value %d: error %v, want ErrPLIORange", v, err)
		}
	}
	// The boundaries themselves are legal.
	src := make([]byte, 2*4)
	binary.BigEndian.PutUint32(src[4:], 16777215)
	if _, err := enc.Encode(src, make([]byte, 1024), 2, 4); err != nil {
		t.Errorf("PLIO_1 rejected the legal maximum 16777215: %v", err)
	}
}

// TestEncodersRefuseBytepix8 pins the narrowed claim: cfitsio has no
// 64-bit Rice coder (ricecomp.c: fits_rcomp, _short, _byte only) and
// cannot write a compressed BITPIX 64 image, so with no reference to be
// byte-identical to, the RICE_1 and HCOMPRESS_1 encoders refuse BYTEPIX 8
// with ErrUnsupportedCompression instead of writing an unverifiable
// stream. Both are reachable through the public SelectEncoder.
func TestEncodersRefuseBytepix8(t *testing.T) {
	src := make([]byte, 16*8)
	for i := range src {
		src[i] = byte(i * 37)
	}
	for _, a := range []Algorithm{RICE1, HCOMPRESS1} {
		enc, err := SelectEncoder(a, Params{"BLOCKSIZE": 32, "BYTEPIX": 8})
		if err != nil {
			if errors.Is(err, ErrUnsupportedCompression) {
				continue // refused already at selection
			}
			t.Fatalf("%s: SelectEncoder: %v", a, err)
		}
		if s, ok := enc.(interface{ SetShape(nx, ny int) }); ok {
			s.SetShape(4, 4)
		}
		n, err := enc.Encode(src, make([]byte, 4096), 16, 8)
		if !errors.Is(err, ErrUnsupportedCompression) {
			t.Errorf("%s BYTEPIX 8: Encode returned (%d, %v), want ErrUnsupportedCompression", a, n, err)
		}
	}
}
