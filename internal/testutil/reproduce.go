package testutil

import (
	"bytes"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// Helpers for the *Reproduce* tests (docs/VALIDATION.md rule 2, tier 2):
// each re-runs a golden generator (interop.go: MakeVerify, RunIn) and
// requires the committed bytes back (SameFiles). A missing tool is a
// failure naming it; a generator that does not reproduce the committed
// bytes is a failure.

func lastLines(b []byte, n int) string {
	lines := strings.Split(strings.TrimRight(string(b), "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}

// CopyTree copies the regular files under src into dst (created).
func CopyTree(t testing.TB, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		if !d.Type().IsRegular() {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(target, b, 0o644)
	})
	if err != nil {
		t.Fatalf("copying %s: %v", src, err)
	}
}

// SameFiles requires every named file to be byte-identical in got and
// want (directories); names nil compares every file under want and
// requires got to have no extra files.
func SameFiles(t testing.TB, got, want string, names []string) {
	t.Helper()
	all := names == nil
	if all {
		names = listFiles(t, want)
		if g := listFiles(t, got); strings.Join(g, "\n") != strings.Join(names, "\n") {
			t.Errorf("regenerated file set differs from the committed one:\n got  %v\n want %v", g, names)
		}
	}
	if len(names) == 0 {
		t.Fatalf("no files to compare under %s", want)
	}
	for _, n := range names {
		w, err := os.ReadFile(filepath.Join(want, n))
		if err != nil {
			t.Errorf("committed golden missing (failure, not a skip): %v", err)
			continue
		}
		g, err := os.ReadFile(filepath.Join(got, n))
		if err != nil {
			t.Errorf("generator did not write %s: %v", n, err)
			continue
		}
		if strings.HasSuffix(n, ".gz") {
			// A gzipped golden (ReadGolden): the decompressed bytes are
			// the harness output; the compressed bytes depend on the
			// zlib build, so they are not compared.
			gu, gerr := Gunzip(g)
			wu, werr := Gunzip(w)
			if gerr != nil || werr != nil {
				t.Errorf("%s: gzip: regenerated %v, committed %v", n, gerr, werr)
				continue
			}
			g, w = gu, wu
		}
		if !bytes.Equal(g, w) {
			t.Errorf("%s: regenerated bytes differ from the committed golden (%d vs %d bytes)", n, len(g), len(w))
		}
	}
}

func listFiles(t testing.TB, dir string) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.Type().IsRegular() {
			rel, _ := filepath.Rel(dir, p)
			out = append(out, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("listing %s: %v", dir, err)
	}
	sort.Strings(out)
	return out
}
